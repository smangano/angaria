  // A pipe write generates SIGPIPE in its calling thread. Temporarily block
  // that signal rather than changing the process-wide disposition; consume only
  // a signal generated by this write, retaining any signal that was pending
  // before it and restoring the caller's original mask on every exit path.
  class BlockedSigpipe
  {
  public:
    BlockedSigpipe()
    {
      sigemptyset(&_signal);
      sigaddset(&_signal, SIGPIPE);
      const auto error = ::pthread_sigmask(SIG_BLOCK, &_signal, &_previous);
      if (error != 0)
      {
        throw std::system_error(error, std::generic_category(), "block registration worker SIGPIPE");
      }
      sigset_t pending;
      if (::sigpending(&pending) == -1)
      {
        const auto pendingError = errno;
        ::pthread_sigmask(SIG_SETMASK, &_previous, nullptr);
        throw std::system_error(pendingError, std::generic_category(), "inspect pending SIGPIPE");
      }
      _wasPending = sigismember(&pending, SIGPIPE) == 1;
    }

    ~BlockedSigpipe()
    {
      ::pthread_sigmask(SIG_SETMASK, &_previous, nullptr);
    }

    BlockedSigpipe(const BlockedSigpipe&) = delete;
    BlockedSigpipe& operator=(const BlockedSigpipe&) = delete;

    void consume_generated()
    {
      if (_wasPending)
      {
        return;
      }
      sigset_t pending;
      if (::sigpending(&pending) == -1)
      {
        throw std::system_error(errno, std::generic_category(), "inspect generated SIGPIPE");
      }
      // SIG_IGN can leave no pending signal even though write returned EPIPE.
      if (sigismember(&pending, SIGPIPE) == 1)
      {
        int received{};
        int error;
        do
        {
          error = ::sigwait(&_signal, &received);
        } while (error == EINTR);
        if (error != 0)
        {
          throw std::system_error(error, std::generic_category(), "consume registration worker SIGPIPE");
        }
      }
    }

  private:
    sigset_t _signal{};
    sigset_t _previous{};
    bool _wasPending{};
  };

  // Pipe reports establish exact process boundaries; no sleep decides when a
  // registration has committed. Every assertion path closes/reaps the worker,
  // and a deadline makes a missing checkpoint fail rather than hang the suite.
  class TopologyWorker
  {
  public:
    TopologyWorker(const fs::path& directory, const std::string& mode, unsigned kind,
                 unsigned actor = 1, std::uint64_t raw = 0, std::uint32_t version = 1,
                 const std::string& name = "Registered", const std::string& doc = "durable metadata",
                 mapped::JournalCheckpoint point = mapped::JournalCheckpoint::Prepared,
                 std::uint64_t index = 0)
    {
      std::array<int, 2> output{-1, -1};
      std::array<int, 2> input{-1, -1};
      if (::pipe(output.data()) == -1 || ::pipe(input.data()) == -1)
      {
        close_fds(output, input);
        throw std::runtime_error("registration worker pipe failed");
      }
      int error{};
      for (auto* pair : {&output, &input})
      {
        for (auto& fd : *pair)
        {
          // Keep spawn's sources distinct from stdin/stdout even when the
          // invoking test environment left a standard descriptor closed.
          if (fd <= STDERR_FILENO)
          {
            const auto replacement = ::fcntl(fd, F_DUPFD_CLOEXEC, STDERR_FILENO + 1);
            if (replacement == -1)
            {
              error = errno;
              break;
            }
            ::close(fd);
            fd = replacement;
          }
          else if (::fcntl(fd, F_SETFD, FD_CLOEXEC) == -1)
          {
            error = errno;
            break;
          }
        }
        if (error != 0)
        {
          break;
        }
      }
      posix_spawn_file_actions_t actions;
      if (error == 0)
      {
        error = ::posix_spawn_file_actions_init(&actions);
        if (error == 0)
        {
          error = ::posix_spawn_file_actions_adddup2(&actions, output[1], STDOUT_FILENO);
          error = error == 0 ? ::posix_spawn_file_actions_adddup2(&actions, input[0], STDIN_FILENO) : error;
          for (const auto fd : {output[0], output[1], input[0], input[1]})
          {
            error = error == 0 ? ::posix_spawn_file_actions_addclose(&actions, fd) : error;
          }
          const std::array<std::string, 11> values{
              ANGARIA_NATIVE_TOPOLOGY_WORKER, mode, directory.string(), std::to_string(actor),
              std::to_string(kind), std::to_string(raw),
              std::to_string(version), name, doc,
              std::to_string(static_cast<unsigned>(point)), std::to_string(index)};
          std::array<char*, 12> arguments{};
          for (std::size_t position = 0; position != values.size(); ++position)
          {
            arguments[position] = const_cast<char*>(values[position].c_str());
          }
          error = error == 0 ? ::posix_spawn(&_pid, values[0].c_str(), &actions, nullptr,
                                            arguments.data(), environ) : error;
          ::posix_spawn_file_actions_destroy(&actions);
        }
      }
      if (error != 0)
      {
        close_fds(output, input);
        throw std::system_error(error, std::generic_category(), "spawn registration worker");
      }
      ::close(output[1]);
      ::close(input[0]);
      _output = output[0];
      _input = input[1];
    }

    ~TopologyWorker()
    {
      release();
      if (_pid > 0)
      {
        ::kill(_pid, SIGKILL);
        int status{};
        while (::waitpid(_pid, &status, 0) == -1 && errno == EINTR)
        {
        }
      }
      if (_output != -1)
      {
        ::close(_output);
      }
    }

    TopologyWorker(const TopologyWorker&) = delete;
    TopologyWorker& operator=(const TopologyWorker&) = delete;

    char receive()
    {
      char value{};
      receive_exact(&value, sizeof(value));
      return value;
    }

    std::uint64_t receive_number()
    {
      std::uint64_t value{};
      receive_exact(&value, sizeof(value));
      return value;
    }

    Outcome receive_outcome()
    {
      return Outcome{receive(), receive_number()};
    }

    void proceed()
    {
      BlockedSigpipe blocked;
      const char continuation = 'C';
      ssize_t count;
      do
      {
        count = ::write(_input, &continuation, 1);
      } while (count == -1 && errno == EINTR);
      const auto writeError = errno;
      if (count == -1 && writeError == EPIPE)
      {
        blocked.consume_generated();
      }
      if (count != 1)
      {
        throw std::system_error(count == -1 ? writeError : EIO, std::generic_category(),
                                "registration worker continuation failed");
      }
    }

    void terminate_at_checkpoint()
    {
      if (receive() != 'R')
      {
        throw std::runtime_error("registration worker reached an unexpected checkpoint");
      }
      terminate();
    }

    void terminate()
    {
      if (::kill(_pid, SIGKILL) == -1)
      {
        throw std::runtime_error("registration worker termination failed");
      }
      const auto status = wait_for_exit();
      if (!WIFSIGNALED(status) || WTERMSIG(status) != SIGKILL)
      {
        throw std::runtime_error("registration worker did not stop at SIGKILL");
      }
    }

    int finish()
    {
      release();
      const auto status = wait_for_exit();
      return WIFEXITED(status) ? WEXITSTATUS(status) : 128 + WTERMSIG(status);
    }

  private:
    static void close_fds(const std::array<int, 2>& output, const std::array<int, 2>& input)
    {
      for (const auto fd : {output[0], output[1], input[0], input[1]})
      {
        if (fd != -1)
        {
          ::close(fd);
        }
      }
    }

    void release()
    {
      if (_input != -1)
      {
        ::close(std::exchange(_input, -1));
      }
    }

    void receive_exact(void* data, std::size_t length)
    {
      auto* bytes = static_cast<char*>(data);
      const auto deadline = std::chrono::steady_clock::now() + 3s;
      while (length != 0)
      {
        const auto remaining = std::chrono::duration_cast<std::chrono::milliseconds>(
            deadline - std::chrono::steady_clock::now()).count();
        if (remaining <= 0)
        {
          throw std::runtime_error("registration worker report deadline expired");
        }
        pollfd event{_output, POLLIN, 0};
        const auto ready = ::poll(&event, 1, static_cast<int>(remaining));
        if (ready == -1 && errno == EINTR)
        {
          continue;
        }
        if (ready <= 0)
        {
          throw std::runtime_error("registration worker did not report");
        }
        const auto count = ::read(_output, bytes, length);
        if (count > 0)
        {
          bytes += count;
          length -= static_cast<std::size_t>(count);
        }
        else if (count != -1 || errno != EINTR)
        {
          throw std::runtime_error("registration worker exited without its report");
        }
      }
    }

    int wait_for_exit()
    {
      const auto deadline = std::chrono::steady_clock::now() + 3s;
      for (;;)
      {
        int status{};
        const auto result = ::waitpid(_pid, &status, WNOHANG);
        if (result == _pid)
        {
          _pid = -1;
          return status;
        }
        if (result == -1 && errno != EINTR)
        {
          throw std::runtime_error("registration worker wait failed");
        }
        if (std::chrono::steady_clock::now() >= deadline)
        {
          throw std::runtime_error("registration worker exit deadline expired");
        }
        ::poll(nullptr, 0, 1);
      }
    }

    pid_t _pid{-1};
    int _output{-1};
    int _input{-1};
  };

  class TopologyRecoveryTest : public testing::Test
  {
  protected:
    void SetUp() override
    {
      auto pattern = (fs::temp_directory_path() / "angaria-topology-processes-XXXXXX").string();
      ASSERT_NE(::mkdtemp(pattern.data()), nullptr);
      _root = pattern;
    }

    void TearDown() override
    {
      std::error_code ignored;
      fs::remove_all(_root, ignored);
    }

    static std::shared_ptr<runtime::SessionState> state(const fs::path& directory)
    {
      auto result = std::make_shared<runtime::SessionState>();
      result->_directory = fs::canonical(directory);
      result->_controller = require_value(mapped::SessionController::open_existing(directory));
      return result;
    }

    static mapped::JournalSnapshot snapshot(const fs::path& directory)
    {
      runtime::RuntimeAccess access(state(directory));
      return access._snapshot;
    }

    static std::vector<std::string> claims(const fs::path& directory)
    {
      std::vector<std::string> names;
      for (const auto& entry : fs::directory_iterator(directory / "claims"))
      {
        names.push_back(entry.path().filename().string());
      }
      std::sort(names.begin(), names.end());
      return names;
    }

    Session create_detached(const fs::path& directory, bool secondActor = false)
    {
      SessionOptions options;
      options._name = "Topology processes";
      options._directory = directory;
      options._maxLogBytes = 2097152;
      options._limits = CapacityLimits::empty().tasks(4).queues(8).source_sets(8)
          .publishing_sets(8).memberships_per_set(8);
      TaskDescriptor creator;
      creator._name = "Creator";
      auto created = require_value(Session::create(options, creator));
      auto registry = created._creator.registry();
      if (secondActor)
      {
        TaskDescriptor other;
        other._name = "OtherActor";
        require_value(registry.register_task(other));
      }
      SourceQueueSetDescriptor source;
      source._name = "Inputs";
      source._owner = TaskId{1};
      require_value(registry.register_source_set(source));
      QueueDescriptor queue;
      queue._name = "Input";
      queue._producer = TaskId{1};
      queue._sourceSet = SourceQueueSetId{1};
      require_value(registry.register_queue(queue));
      return std::move(created._session);
    }

    static Result<std::uint64_t> find(Registry registry, unsigned kind, const std::string& name = "Registered")
    {
      const auto convert = [](auto result) -> Result<std::uint64_t>
      {
        if (const auto* error = std::get_if<Error>(&result))
        {
          return *error;
        }
        return static_cast<std::uint64_t>(std::get<0>(result));
      };
      if (kind == 0)
      {
        return convert(registry.find_source_set(name));
      }
      if (kind == 1)
      {
        return convert(registry.find_queue(name));
      }
      return convert(registry.find_publishing_set(name));
    }

    static std::uint64_t retry(Registry registry, unsigned kind)
    {
      if (kind == 0)
      {
        SourceQueueSetDescriptor source;
        source._name = "Registered";
        source._owner = TaskId{1};
        source._doc = "durable metadata";
        return static_cast<std::uint64_t>(require_value(registry.register_source_set(source)));
      }
      if (kind == 1)
      {
        QueueDescriptor queue;
        queue._name = "Registered";
        queue._producer = TaskId{1};
        queue._sourceSet = SourceQueueSetId{1};
        queue._priority = 7;
        queue._doc = "durable metadata";
        return static_cast<std::uint64_t>(require_value(registry.register_queue(queue)));
      }
      PublishingQueueSetDescriptor publishing;
      publishing._name = "Registered";
      publishing._owner = TaskId{1};
      publishing._destinations = {QueueId{1}};
      publishing._doc = "durable metadata";
      return static_cast<std::uint64_t>(require_value(registry.register_publishing_set(publishing)));
    }

    static void check_members(Registry registry, std::size_t count)
    {
      const auto members = require_value(registry.source_members(SourceQueueSetId{1}));
      ASSERT_EQ(members.size(), count);
      EXPECT_EQ(members.front(), QueueId{1});
      for (const auto member : members)
      {
        EXPECT_EQ(require_value(registry.describe_queue(member))._sourceSet, SourceQueueSetId{1});
        EXPECT_EQ(require_value(registry.state(member)), EntityState::Draft);
      }
    }

    fs::path _root;
  };

  // The second executable uses only public Session/Registry calls. It verifies
  // resolved policies, Draft state, attribution, and the inverse Source relation.
  TEST_F(TopologyRecoveryTest, IndependentProcessesDiscoverEveryDraftEntityKind)
  {
    for (unsigned kind = 0; kind != 3; ++kind)
    {
      SCOPED_TRACE(kind);
      const auto directory = _root / std::to_string(kind);
      auto session = create_detached(directory);
      const auto files = claims(directory);
      const auto before = snapshot(directory);
      TopologyWorker writer(directory, "register", kind);
      ASSERT_EQ(writer.receive(), 'R');
      writer.proceed();
      const auto result = writer.receive_outcome();
      ASSERT_EQ(result._marker, 'A');
      EXPECT_EQ(result._value, 2u);
      EXPECT_EQ(writer.finish(), 0);
      TopologyWorker reader(directory, "inspect", kind);
      ASSERT_EQ(reader.receive(), 'I');
      EXPECT_EQ(reader.receive_number(), 2u);
      EXPECT_EQ(reader.receive_number(), 1u);
      EXPECT_EQ(reader.receive_number(), before._revision + 1);
      EXPECT_EQ(reader.receive_number(), kind == 0 ? 0u : kind == 1 ? 2u : 1u);
      EXPECT_EQ(reader.finish(), 0);
      check_members(session.registry(), kind == 1 ? 2 : 1);
      EXPECT_EQ(claims(directory), files);
    }
  }

  // Distinct live actors race identical, conflicting, and different names. The
  // gate makes both identity allocation and a Queue's Source revision atomic.
  TEST_F(TopologyRecoveryTest, ConcurrentRegistrarsPreserveIdentityAndSourceMembership)
  {
    for (unsigned kind = 0; kind != 3; ++kind)
    {
      for (unsigned scenario = 0; scenario != 3; ++scenario)
      {
        SCOPED_TRACE(kind);
        SCOPED_TRACE(scenario);
        const auto directory = _root / (std::to_string(kind) + "-race-" + std::to_string(scenario));
        auto session = create_detached(directory, true);
        const auto before = snapshot(directory);
        TopologyWorker first(directory, "register", kind, 1);
        TopologyWorker second(directory, "register", kind, 2, 0, 1,
                              scenario == 2 ? "Other" : "Registered",
                              scenario == 1 ? "conflicting documentation" : "durable metadata");
        ASSERT_EQ(first.receive(), 'R');
        ASSERT_EQ(second.receive(), 'R');
        first.proceed();
        second.proceed();
        const auto left = first.receive_outcome();
        const auto right = second.receive_outcome();
        if (scenario == 1)
        {
          const auto& accepted = left._marker == 'A' ? left : right;
          const auto& rejected = left._marker == 'A' ? right : left;
          EXPECT_EQ(accepted._marker, 'A');
          EXPECT_EQ(accepted._value, 2u);
          EXPECT_EQ(rejected._marker, 'E');
          EXPECT_EQ(rejected._value, static_cast<std::uint64_t>(ErrorCode::Conflict));
        }
        else
        {
          EXPECT_EQ(left._marker, 'A');
          EXPECT_EQ(right._marker, 'A');
          if (scenario == 0)
          {
            EXPECT_EQ(left._value, 2u);
            EXPECT_EQ(right._value, 2u);
          }
          else
          {
            const std::vector<std::uint64_t> identities{std::min(left._value, right._value), std::max(left._value, right._value)};
            EXPECT_EQ(identities, (std::vector<std::uint64_t>{2, 3}));
          }
        }
        EXPECT_EQ(snapshot(directory)._revision, before._revision + (scenario == 2 ? 2 : 1));
        check_members(session.registry(), kind == 1 ? (scenario == 2 ? 3 : 2) : 1);
        EXPECT_EQ(first.finish(), 0);
        EXPECT_EQ(second.finish(), 0);
      }
    }
  }

  // Source and Publishing sets share their name/ID namespace even though each
  // has a separately bounded allocation table and a distinct public ID type.
  TEST_F(TopologyRecoveryTest, ConcurrentQueueSetKindsCannotClaimTheSameName)
  {
    const auto directory = _root / "shared-namespace";
    auto session = create_detached(directory, true);
    const auto before = snapshot(directory);
    TopologyWorker source(directory, "register", 0, 1);
    TopologyWorker publishing(directory, "register", 2, 2);
    ASSERT_EQ(source.receive(), 'R');
    ASSERT_EQ(publishing.receive(), 'R');
    source.proceed();
    publishing.proceed();
    const auto left = source.receive_outcome();
    const auto right = publishing.receive_outcome();
    EXPECT_NE(left._marker, right._marker);
    EXPECT_EQ(left._marker == 'A' ? left._value : right._value, 2u);
    EXPECT_EQ(left._marker == 'E' ? left._value : right._value, static_cast<std::uint64_t>(ErrorCode::Conflict));
    EXPECT_EQ(snapshot(directory)._revision, before._revision + 1);
    EXPECT_EQ(source.finish(), 0);
    EXPECT_EQ(publishing.finish(), 0);
  }

  // Real SIGKILL cuts cover preacceptance rollback and accepted partial index /
  // membership redo. A Queue and its revised Source must appear together.
  TEST_F(TopologyRecoveryTest, CrashCutsExposeOnlyWholeDraftTopologyUpdates)
  {
    struct Cut
    {
      mapped::JournalCheckpoint _point;
      std::uint64_t _index;
      bool _accepted;
    };
    const std::array<Cut, 10> cuts{{
        {mapped::JournalCheckpoint::JournalBodyWord, 0, false},
        {mapped::JournalCheckpoint::Prepared, 0, false},
        {mapped::JournalCheckpoint::FileGrowth, 0, false},
        {mapped::JournalCheckpoint::RecordBodyWord, 0, false},
        {mapped::JournalCheckpoint::RecordReady, 0, false},
        {mapped::JournalCheckpoint::Committed, 0, true},
        {mapped::JournalCheckpoint::RedoWord, 0, true},
        {mapped::JournalCheckpoint::RedoWord, 3, true},
        {mapped::JournalCheckpoint::EpilogueWord, 2, true},
        {mapped::JournalCheckpoint::Idle, 0, true},
    }};
    for (unsigned kind = 0; kind != 3; ++kind)
    {
      std::vector<Cut> applicable(cuts.begin(), cuts.end());
      if (kind == 1)
      {
        // The Queue batch has a second definition/index and two membership
        // rows. Stop inside each part, not only at the first Queue index word.
        applicable.push_back({mapped::JournalCheckpoint::RecordReady, 1, false});
        applicable.push_back({mapped::JournalCheckpoint::RedoWord, 5, true});
        applicable.push_back({mapped::JournalCheckpoint::RedoWord, 9, true});
        applicable.push_back({mapped::JournalCheckpoint::RecordCommitted, 1, true});
      }
      for (std::size_t cut = 0; cut != applicable.size(); ++cut)
      {
        SCOPED_TRACE(kind);
        SCOPED_TRACE(cut);
        const auto directory = _root / (std::to_string(kind) + "-crash-" + std::to_string(cut));
        auto session = create_detached(directory);
        const auto before = snapshot(directory);
        const auto files = claims(directory);
        const auto& point = applicable[cut];
        TopologyWorker writer(directory, "crash", kind, 1, 0, 1, "Registered", "durable metadata", point._point, point._index);
        writer.terminate_at_checkpoint();
        const auto found = find(session.registry(), kind);
        if (point._accepted)
        {
          EXPECT_EQ(require_value(found), 2u);
        }
        else
        {
          EXPECT_TRUE(has_error(found, ErrorCode::NotFound));
        }
        const auto recovered = snapshot(directory);
        EXPECT_EQ(recovered._revision, before._revision + (point._accepted ? 1 : 0));
        EXPECT_EQ(recovered._tail == before._tail, !point._accepted);
        check_members(session.registry(), kind == 1 && point._accepted ? 2 : 1);
        auto actor = require_value(session.attach_task(TaskId{1}));
        const auto beforeRetry = snapshot(directory);
        EXPECT_EQ(retry(actor.registry(), kind), 2u);
        EXPECT_EQ(snapshot(directory)._revision, before._revision + 1);
        if (point._accepted)
        {
          EXPECT_EQ(snapshot(directory), beforeRetry);
        }
        check_members(session.registry(), kind == 1 ? 2 : 1);
        EXPECT_EQ(claims(directory), files);
      }
    }
  }

  // Recovery can itself stop after only part of a committed Queue/Source batch.
  // Repeating repair must retain the accepted identity and both relationships.
  TEST_F(TopologyRecoveryTest, InterruptedRepairRetainsAcceptedDefinitionsAndMembership)
  {
    for (unsigned kind = 0; kind != 3; ++kind)
    {
      const auto directory = _root / (std::to_string(kind) + "-repair");
      auto session = create_detached(directory);
      const auto before = snapshot(directory);
      TopologyWorker writer(directory, "crash", kind, 1, 0, 1, "Registered", "durable metadata", mapped::JournalCheckpoint::Committed);
      writer.terminate_at_checkpoint();
      TopologyWorker first(directory, "recover", kind, 1, 0, 1, "Registered", "durable metadata", mapped::JournalCheckpoint::RedoWord, kind == 1 ? 5 : 1);
      first.terminate_at_checkpoint();
      TopologyWorker second(directory, "recover", kind, 1, 0, 1, "Registered", "durable metadata",
                            kind == 1 ? mapped::JournalCheckpoint::RedoWord : mapped::JournalCheckpoint::RecordCommitted,
                            kind == 1 ? 9 : 0);
      second.terminate_at_checkpoint();
      if (kind == 1)
      {
        TopologyWorker third(directory, "recover", kind, 1, 0, 1, "Registered", "durable metadata",
                             mapped::JournalCheckpoint::RecordCommitted, 1);
        third.terminate_at_checkpoint();
      }
      EXPECT_EQ(require_value(find(session.registry(), kind)), 2u);
      EXPECT_EQ(snapshot(directory)._revision, before._revision + 1);
      check_members(session.registry(), kind == 1 ? 2 : 1);
      auto actor = require_value(session.attach_task(TaskId{1}));
      const auto beforeRetry = snapshot(directory);
      EXPECT_EQ(retry(actor.registry(), kind), 2u);
      EXPECT_EQ(snapshot(directory), beforeRetry);
    }
  }

  // I/O failure before acceptance rolls back; accepted repair returns success
  // or OutcomeUnknown. Lookup and exact retry settle the same topology update.
  TEST_F(TopologyRecoveryTest, IoOutcomesResolveThroughLookupAndExactRetry)
  {
    for (unsigned kind = 0; kind != 3; ++kind)
    {
      for (const auto& mode : {std::string{"io_before"}, std::string{"io_after"}, std::string{"io_unknown"}})
      {
        SCOPED_TRACE(kind);
        SCOPED_TRACE(mode);
        const auto directory = _root / (std::to_string(kind) + mode);
        auto session = create_detached(directory);
        const auto before = snapshot(directory);
        TopologyWorker writer(directory, mode, kind);
        const auto result = writer.receive_outcome();
        const bool accepted = mode != "io_before";
        EXPECT_EQ(result._marker, mode == "io_after" ? 'A' : 'E');
        EXPECT_EQ(result._value, mode == "io_after" ? 2u : static_cast<std::uint64_t>(
            accepted ? ErrorCode::OutcomeUnknown : ErrorCode::IoError));
        const auto found = find(session.registry(), kind);
        if (accepted)
        {
          EXPECT_EQ(require_value(found), 2u);
        }
        else
        {
          EXPECT_TRUE(has_error(found, ErrorCode::NotFound));
        }
        EXPECT_EQ(snapshot(directory)._revision, before._revision + (accepted ? 1 : 0));
        check_members(session.registry(), kind == 1 && accepted ? 2 : 1);
        writer.proceed();
        const auto retried = writer.receive_outcome();
        EXPECT_EQ(retried._marker, 'A');
        EXPECT_EQ(retried._value, 2u);
        EXPECT_EQ(snapshot(directory)._revision, before._revision + 1);
        check_members(session.registry(), kind == 1 ? 2 : 1);
        EXPECT_EQ(writer.finish(), 0);
      }
    }
  }
